import { expect, test } from "@playwright/test";

test("inline user search and separate role, status, and date filters", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addInitScript(() => localStorage.setItem("shinigacim-auth", JSON.stringify({ state: { user: { id: "admin", username: "admin", role: "admin", status: "active", createdAt: "2026-01-01" }, accessToken: "test", refreshToken: "test" }, version: 0 })));
  const users = [{ id: "a", username: "Alice", createdAt: "2026-01-01", role: "admin", status: "active" }, { id: "b", username: "Alina", createdAt: "2026-06-01", role: "user", status: "pending_approval" }, { id: "c", username: "Bob", createdAt: "2026-08-01", role: "user", status: "disabled" }].map((user) => ({ ...user, lastSeenAt: null }));
  await page.route(/^https?:\/\/[^/]+\/api\//, route => route.fulfill({ json: new URL(route.request().url()).pathname === "/api/users" ? users : [] }));
  await page.route("**/hubs/**", route => route.abort());
  await page.goto("/users");
  const rows = page.locator(".mobile-users__item");
  await expect(rows).toHaveCount(3);
  const input = page.getByRole("searchbox", { name: "Search users" });
  await input.click();
  await expect(input).toBeFocused();
  await input.fill("Al");
  await expect(rows).toHaveCount(3);
  await input.fill("Ali");
  await expect(rows).toHaveCount(2);
  const trigger = page.getByRole("button", { name: "Filters" });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "Filters" });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText("Who", { exact: true })).toHaveCount(0);
  await dialog.getByRole("combobox", { name: "Role" }).selectOption("user");
  await dialog.getByRole("combobox", { name: "Status" }).selectOption("pending_approval");
  await dialog.getByText("When", { exact: true }).click();
  await dialog.getByLabel("From").fill("2026-04-01");
  await dialog.getByRole("button", { name: "Search", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await expect(rows).toHaveCount(1);
  await expect(rows.first()).toContainText("Alina");
  await trigger.click();
  await dialog.getByRole("button", { name: "Clear all" }).click();
  await expect(dialog.getByRole("combobox", { name: "Role" })).toHaveValue("");
  await expect(dialog.getByRole("combobox", { name: "Status" })).toHaveValue("");
  await dialog.getByRole("button", { name: "Search", exact: true }).click();
  await expect(rows).toHaveCount(2);
});
